// French punctuation: a no-break space before : ; ? ! and inside « », a narrow one before %, so the sign never starts or ends
// a line alone
const nbsp = (s) => s.replace(/ ([:;?!])/g, " $1").replace(/« /g, "« ").replace(/ »/g, " »")
  // and the narrow no-break space before %, as Intl writes it (73,5 %), so "50 %" never parts at a line end
  .replace(/ %/g, " %");
for (const [k, v] of Object.entries(FR)) FR[k] = typeof v === "string" ? nbsp(v) : Object.fromEntries(Object.entries(v).map(([f, s]) => [f, nbsp(s)]));

export const STRINGS = { en: EN, fr: FR };
export const LANGS = ["en", "fr"];
const PLURAL = { en: new Intl.PluralRules("en"), fr: new Intl.PluralRules("fr") };

function raw(key, p) {
  const lang = getLang();
  let s = STRINGS[lang][key] ?? EN[key];
  if (s == null) { console.warn("i18n: no string for", key); return key; }
  if (typeof s === "object") s = s[PLURAL[lang].select(typeof p.count === "number" ? p.count : typeof p.n === "number" ? p.n : 0)] ?? s.other;
  return s;
}

const show = (v) => (typeof v === "number" && Number.isInteger(v) ? fmtInt(v) : String(v));

/** The string `key` in the current language, placeholders filled. `**` marks are dropped (tx() draws them bold). */
export function t(key, p = {}) {
  return raw(key, p).replace(/\{(\w+)\}/g, (m, k) => (k in p ? show(p[k]) : m)).replace(/\*\*/g, "");
}

/** Like t(), but returns nodes for h(): a parameter may be a Node (a card chip, an icon) and `**text**` becomes <b>. */
export function tx(key, p = {}) {
  const out = [];
  raw(key, p).split(/(\*\*[^*]+\*\*)/).forEach((part) => {
    const bold = /^\*\*[^*]+\*\*$/.test(part);
    const kids = [];
    (bold ? part.slice(2, -2) : part).split(/(\{\w+\})/).forEach((bit) => {
      const m = /^\{(\w+)\}$/.exec(bit);
      if (m && m[1] in p) kids.push(p[m[1]] instanceof Node ? p[m[1]] : show(p[m[1]]));
      else if (bit) kids.push(bit);
    });
    if (bold) out.push(h("b", kids)); else out.push(...kids);
  });
  return out;
}

/** "1.15 million" / "1,15 million": a large count of matches, rounded for running text. */
export const millions = (n) => t("num.million", { n: dec(n / 1e6, 2), count: n / 1e6 });

/** 1 -> "1st" / "1er", 105 -> "105th" / "105e". */
export function ord(n) {
  if (getLang() === "fr") return n === 1 ? "1er" : `${n}e`;
  return n + (n % 100 >= 11 && n % 100 <= 13 ? "th" : { 1: "st", 2: "nd", 3: "rd" }[n % 10] || "th");
}

/**
 * Fills the static markup of index.html: data-i18n (text), data-i18n-aria (aria-label), data-i18n-title (title),
 * data-i18n-ph (placeholder). Run at start and on every language change.
 */
export function applyStatic(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll("[data-i18n-ph]")) el.placeholder = t(el.dataset.i18nPh);
}
